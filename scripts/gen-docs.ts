/**
 * Generates reference docs from the registries so the manual never drifts from the code.
 * Run: npm run gen-docs. Writes docs/reference/*.md.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { MODULES } from '../src/modules/registry';
import { SETTINGS_GROUPS } from '../src/lib/settings/registry';
import { ENV_VARS } from '../src/lib/env-registry';
import { BUILT_IN_ROLES } from '../src/lib/auth/areas';
import { RESOURCES } from '../src/lib/admin/registry';
import { walkFields } from '../src/lib/admin/fields';
import { BLOCKS } from '../src/lib/blocks/catalog';
import { PRESETS } from '../src/lib/theme/presets';

const out = 'docs/reference';
mkdirSync(out, { recursive: true });
const header = (title: string) => `# ${title}\n\nGenerated by \`npm run gen-docs\`. Do not edit by hand.\n\n`;
const cell = (s: string) => s.replace(/\|/g, '\\|');

const labelOf = (id: string) => MODULES.find((m) => m.id === id)?.label ?? id;
const needs = (req: readonly (readonly string[])[]) =>
  req.length === 0 ? 'Nothing' : req.map((c) => c.map(labelOf).join(' or ')).join(', and ');

writeFileSync(
  `${out}/modules.md`,
  header('Modules') +
    '| Id | Name | What it adds | Needs | Default | Public routes |\n| --- | --- | --- | --- | --- | --- |\n' +
    MODULES.map(
      (m) =>
        `| \`${m.id}\` | ${m.label} | ${cell(m.description)} | ${needs(m.requires)} | ${
          m.alwaysOn ? 'Always on' : m.devOnly ? 'On in development only' : m.defaultOn ? 'On' : 'Off'
        } | ${m.routes.map((r) => `\`${r}\``).join(', ') || 'None'} |`,
    ).join('\n') +
    '\n',
);

writeFileSync(
  `${out}/settings.md`,
  header('Settings groups') +
    SETTINGS_GROUPS.map((g) => {
      const fields = g.fields.length
        ? '| Field | Type | Help |\n| --- | --- | --- |\n' +
          g.fields.map((f) => `| ${f.label} (\`${f.name}\`) | ${f.type} | ${cell(f.info)} |`).join('\n')
        : `Managed on its own screen${g.customScreen ? ` (\`${g.customScreen}\`)` : ''}.`;
      return `## ${g.label} (\`${g.key}\`)\n\n${g.description}\n\nArea: ${g.area}. Module: ${labelOf(g.module)}.\n\n${fields}\n`;
    }).join('\n'),
);

writeFileSync(
  `${out}/environment.md`,
  header('Environment variables') +
    '| Variable | Required | Purpose | Since phase |\n| --- | --- | --- | --- |\n' +
    ENV_VARS.map((v) => `| \`${v.name}\` | ${v.required} | ${cell(v.purpose)} | ${v.phase} |`).join('\n') +
    '\n',
);

writeFileSync(
  `${out}/roles.md`,
  header('Built-in roles') +
    '| Role | Areas |\n| --- | --- |\n' +
    BUILT_IN_ROLES.map((r) => `| ${r.label} (\`${r.id}\`) | ${r.areas.includes('*') ? 'Everything' : r.areas.join(', ')} |`).join('\n') +
    '\n',
);

writeFileSync(
  `${out}/resources.md`,
  header('Admin lists and editors') +
    RESOURCES.map((r) => {
      const traits = [
        r.softDelete ? 'Trash' : null,
        r.revisions ? 'versions' : null,
        r.duplicate ? 'duplicate' : null,
        r.quickEdit?.length ? `quick edit (${r.quickEdit.join(', ')})` : null,
        r.csv ? 'CSV export' : null,
        r.csv?.importKey ? `CSV import matched on ${r.csv.importKey}` : null,
        r.readOnly ? 'read only' : null,
      ].filter(Boolean);
      const rows = [...walkFields(r.fields)]
        .map(({ field, path }) => `| ${field.label} (\`${path}\`) | ${field.type}${field.required ? ', required' : ''}${field.adminOnly ? ', administrators only' : ''} | ${field.tab ?? 'Content'} | ${cell(field.info)} |`)
        .join('\n');
      return `## ${r.labelPlural} (\`/admin/${r.id}\`)\n\n${r.description}\n\nArea: ${r.area}. Module: ${labelOf(r.module)}. ${traits.length ? `Supports ${traits.join(', ')}.` : ''}\n\n| Field | Type | Tab | Help |\n| --- | --- | --- | --- |\n${rows}\n`;
    }).join('\n'),
);

writeFileSync(
  `${out}/blocks.md`,
  header('Page builder blocks') +
    BLOCKS.map((b) => {
      const rows = [...walkFields(b.fields)].map(({ field, path }) => `| ${field.label} (\`${path}\`) | ${field.type}${field.required ? ', required' : ''}${field.adminOnly ? ', administrators only' : ''} | ${cell(field.info)} |`).join('\n');
      return `## ${b.label} (\`${b.type}\`)\n\n${b.description} Group: ${b.group}. Module: ${labelOf(b.module)}.${b.container ? ' Holds other blocks (one level).' : ''}${b.adminOnly ? ' Administrators only.' : ''}\n\n| Field | Type | Help |\n| --- | --- | --- |\n${rows}\n`;
    }).join('\n') +
    `\n## Presets\n\n${PRESETS.map((p) => `- **${p.label}** (\`${p.id}\`): ${p.description}`).join('\n')}\n`,
);

console.info('Reference docs written to docs/reference.');
